#!/usr/bin/env node
// Types for the two JSON files the package ships, and the vocabulary unions
// they are built from. Nothing else is typed: the five modules are
// side-effect imports with no exports, and JSX authors get completion from
// the editor data without a global augmentation of React's own types.
//
// Three files, because a .json entry point cannot carry its own types: each
// JSON export gets a sibling declaration file that package.json's `types`
// condition points at. A `declare module '@foundation/yeti/manifest'` block inside
// yeti.d.ts would be a module augmentation of a specifier that resolves to
// JSON, which every modern resolution mode rejects.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSchema, loadAndMerge, loadVocabulary } from './lib/manifest.js';

export function typeName(vocabulary) {
	return `Yeti${vocabulary.split('-').map((part) => part[0].toUpperCase() + part.slice(1)).join('')}`;
}

const union = (values) => values.map((v) => `'${v.replace(/'/g, "\\'")}'`).join(' | ');

export function renderTypes(merged, vocabulary, tokensSchema) {
	const components = Object.values(merged);
	// The token catalogue's group names are a closed list in the schema, so the
	// type is that list. A tree without the schema (a test fixture) gets string.
	const groups = tokensSchema?.items?.properties?.group?.enum ?? null;
	const lines = [];
	lines.push('// Generated by bin/gen-types.js from the merged manifest. Do not edit.');
	lines.push('');
	for (const name of Object.keys(vocabulary).filter((k) => !k.startsWith('$')).sort()) {
		lines.push(`export type ${typeName(name)} = ${union(vocabulary[name])};`);
	}
	lines.push('');
	lines.push(`export type YetiComponentName = ${union(components.map((c) => c.name))};`);
	lines.push(`export type YetiKind = 'layout' | 'recipe' | 'component' | 'utility';`);
	lines.push(`export type YetiAttributeType = 'enum' | 'boolean' | 'number' | 'string';`);
	lines.push('');
	lines.push('export interface YetiAttribute {');
	lines.push('\tname: `data-${string}`;');
	lines.push('\ttype: YetiAttributeType;');
	lines.push('\tvalues?: string[];');
	lines.push('\tvocabulary?: string;');
	lines.push('\tdefault?: string | number | boolean;');
	lines.push('\tdescription: string;');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiMarker {');
	lines.push('\tname: `data-${string}`;');
	lines.push("\ttype: 'enum' | 'boolean' | 'string';");
	lines.push('\tvalues?: string[];');
	lines.push('\tvocabulary?: string;');
	lines.push('\ton?: string;');
	lines.push('\tdescription: string;');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiChild {');
	lines.push('\tselector: string;');
	lines.push('\tmin?: number;');
	lines.push('\tmax?: number | null;');
	lines.push('\tdescription?: string;');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiToken {');
	lines.push('\tname: `--${string}`;');
	lines.push('\tpublic: boolean;');
	lines.push('\tdescription?: string;');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiEvent {');
	lines.push('\tname: `yeti:${string}`;');
	lines.push('\tdetail?: string;');
	lines.push('\tdescription: string;');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiModule {');
	lines.push('\tmodule: string;');
	lines.push('\toptional: true;');
	lines.push('\tevents?: YetiEvent[];');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiA11y {');
	lines.push('\trole?: string;');
	lines.push('\trequiredAttributes: string[];');
	lines.push('\tkeyboard: Array<{ key: string; action: string }>;');
	lines.push('\tnotes?: string;');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiComponent {');
	// The loader keeps each source manifest's own $schema key, so the shipped
	// components carry it and the schema declares it.
	lines.push('\t$schema?: string;');
	lines.push('\tname: YetiComponentName;');
	lines.push('\tkind: YetiKind;');
	// The docs nav group; optional, and the kind's own name is the fallback.
	lines.push('\tgroup?: string;');
	lines.push('\tdescription: string;');
	lines.push('\tclass: string;');
	lines.push('\tattributes: YetiAttribute[];');
	lines.push("\tclasses: Array<{ name: string; type: 'boolean'; description: string }>;");
	lines.push('\tchildren: YetiChild[];');
	// The loader normalises an absent marker list to [], so the shipped manifest
	// always carries one even where the source manifest omits it.
	lines.push('\tmarkers: YetiMarker[];');
	lines.push('\ttokens: YetiToken[];');
	lines.push('\ta11y: YetiA11y;');
	lines.push('\tjs: YetiModule[] | null;');
	lines.push('\tsupport: { unguarded: string[]; guarded: string[] };');
	lines.push('\tsince: string;');
	lines.push('\texample: string;');
	// How the docs frame the example; optional, and the generator's defaults apply when absent.
	lines.push('\tdemo?: { height?: YetiHeight; width?: YetiWidth; resize?: YetiResize };');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiManifest {');
	lines.push("\tframework: 'yeti';");
	lines.push('\tversion: string;');
	lines.push('\tgenerated: string;');
	lines.push('\tcomponents: Record<YetiComponentName, YetiComponent>;');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiTokenEntry {');
	lines.push('\tname: `--yeti-${string}`;');
	lines.push(`\tgroup: ${groups ? union(groups) : 'string'};`);
	lines.push('\tpublic: true;');
	lines.push('\tdeclared?: boolean;');
	lines.push('\ttheme?: boolean;');
	lines.push('\tdefault: string;');
	lines.push('\tdescription: string;');
	lines.push('}');
	lines.push('');
	lines.push('export interface YetiTokenCatalogue {');
	lines.push("\tframework: 'yeti';");
	lines.push('\tversion: string;');
	lines.push('\tgenerated: string;');
	lines.push('\ttokens: YetiTokenEntry[];');
	lines.push('}');
	lines.push('');
	return lines.join('\n');
}

/** The declaration file that stands in for one of the shipped JSON entry points. */
export function renderModuleTypes(type, binding) {
	return [
		'// Generated by bin/gen-types.js from the merged manifest. Do not edit.',
		`import type { ${type} } from './yeti.js';`,
		`declare const ${binding}: ${type};`,
		`export default ${binding};`,
		'',
	].join('\n');
}

export function writeTypes({ root, merged, vocabulary, tokensSchema = null }) {
	const distDir = path.join(root, 'dist');
	fs.mkdirSync(distDir, { recursive: true });
	const outputs = [];
	const write = (rel, content) => { fs.writeFileSync(path.join(distDir, rel), content); outputs.push(rel); };
	write('yeti.d.ts', renderTypes(merged, vocabulary, tokensSchema));
	write('yeti.manifest.d.ts', renderModuleTypes('YetiManifest', 'manifest'));
	write('yeti.tokens.d.ts', renderModuleTypes('YetiTokenCatalogue', 'tokens'));
	return outputs;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
	const root = process.cwd();
	const schema = loadSchema(path.join(root, 'schema', 'manifest.schema.json'));
	const vocabulary = loadVocabulary(path.join(root, 'schema', 'vocabulary.json'));
	const { merged, errors } = loadAndMerge(path.join(root, 'src'), schema, vocabulary);
	if (errors.length) { for (const e of errors) console.error(`${e.file}: ${e.message}`); process.exit(1); }
	const tokensSchema = loadSchema(path.join(root, 'schema', 'tokens.schema.json'));
	console.log(`gen-types: wrote ${writeTypes({ root, merged, vocabulary, tokensSchema }).join(', ')}`);
}
